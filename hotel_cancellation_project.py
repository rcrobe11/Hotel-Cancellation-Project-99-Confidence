"""## 5. Data Preparation

Our cleaning and preprocessing steps:
1. Drop the `Booking_ID` column (it is just a label, not useful for prediction)
2. Remove impossible arrival dates (Feb 29, 2018)
3. Remove bookings with 0 nights (not a real stay)
4. Remove the extreme price outlier (over $500)
5. Feature engineering: create `total_nights` and `total_guests`
6. Drop `arrival_year` and `arrival_date` (day of month) since they will not help predict future bookings; keep `arrival_month` for seasonality
7. Turn the target into 1 = Canceled, 0 = Not Canceled
8. One-hot encode the text columns (meal plan, room type, market segment)
9. Split into 80% training and 20% testing data
10. Scale (normalize) the numbers so they are on the same scale

There were **no missing values**, so no filling in (imputation) was needed.

### 5.1 Clean the rows
**What this step does:** Removes the ID column and the bad rows we found in Data Understanding.

**Why:** Impossible dates, zero-night stays, and an extreme price would confuse the model.

**What it tells the hotel:** We only lose a very small share of rows (well under 1%), so the data is still a good picture of the hotel's bookings.
"""

clean_df = hotel_df.copy()
rows_before = len(clean_df)

# Step 1: drop the ID column and the helper column we made for charts
clean_df = clean_df.drop(columns=["Booking_ID", "canceled"])

# Step 2: remove impossible dates
arrival_dates = pd.to_datetime(
    dict(year=clean_df["arrival_year"], month=clean_df["arrival_month"], day=clean_df["arrival_date"]),
    errors="coerce")
clean_df = clean_df[arrival_dates.notnull()]

# Step 3: remove bookings with 0 nights
clean_df = clean_df[(clean_df["no_of_weekend_nights"] + clean_df["no_of_week_nights"]) > 0]

# Step 4: remove the extreme price outlier
clean_df = clean_df[clean_df["avg_price_per_room"] <= 500]

rows_after = len(clean_df)
print("Rows before cleaning:", rows_before)
print("Rows after cleaning:", rows_after)
print("Rows removed:", rows_before - rows_after)

"""### 5.2 Feature engineering and encoding
**What this step does:**
- Creates two new, easier-to-understand features: `total_nights` (weekend + week nights) and `total_guests` (adults + children).
- Drops `arrival_year` and `arrival_date`.
- Changes the target to numbers: 1 = Canceled, 0 = Not Canceled.
- **One-hot encodes** the text columns. For example, `market_segment_type` becomes separate 0/1 columns like `market_segment_type_Online`. We use `drop_first=True` to avoid repeating information.

**Why:** Machine learning models need numbers, not text. New features can make patterns clearer.

**What it tells the hotel:** The model can now use every booking detail, including meal plan, room type, and how the booking was made.
"""

# Step 5: new features
clean_df["total_nights"] = clean_df["no_of_weekend_nights"] + clean_df["no_of_week_nights"]
clean_df["total_guests"] = clean_df["no_of_adults"] + clean_df["no_of_children"]

# Step 6: drop columns that will not help predict future bookings
clean_df = clean_df.drop(columns=["arrival_year", "arrival_date"])

# Step 7: target to numbers
clean_df["booking_status"] = clean_df["booking_status"].map({"Canceled": 1, "Not_Canceled": 0})

# Step 8: one-hot encode the text columns
text_columns = ["type_of_meal_plan", "room_type_reserved", "market_segment_type"]
model_df = pd.get_dummies(clean_df, columns=text_columns, drop_first=True, dtype=int)

print("Columns after encoding:", model_df.shape[1])
model_df.head()

"""### 5.3 Split into training and testing sets
**What this step does:** Separates the features (`X`) from the target (`y`), then keeps **80%** of bookings for training and holds back **20%** for testing. `stratify=y` keeps the same 33% cancellation rate in both sets.

**Why:** Testing on data the model has never seen tells us how well it will work on **new** bookings, which is what the hotel actually cares about.
"""

X = model_df.drop(columns=["booking_status"])
y = model_df["booking_status"]

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=random_state, stratify=y)

print("Training rows:", X_train.shape[0])
print("Testing rows:", X_test.shape[0])
print("Number of features:", X_train.shape[1])
print("Cancellation rate in training set:", round(y_train.mean() * 100, 1), "%")
print("Cancellation rate in testing set:", round(y_test.mean() * 100, 1), "%")

"""### 5.4 Normalize (scale) the features
**What this step does:** Uses `StandardScaler` so every feature has an average of 0 and the same spread.

**Why:** Lead time goes up to 443 while most other columns are small numbers like 0, 1, or 2. Logistic regression and SVM can be thrown off by these different scales. (Decision trees and random forests are not affected, but scaling does not hurt them.) We **fit the scaler on the training data only** so no information from the test set leaks into training.
"""

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

print("Average of lead_time after scaling (train):", round(X_train_scaled[:, list(X.columns).index("lead_time")].mean(), 2))

"""## 6. Modeling

**Type of problem:** Supervised **binary classification** (predict Canceled = 1 or Not Canceled = 0).

We build the four models from our proposal:
| Model | Simple explanation |
|---|---|
| **Decision Tree** | Asks a series of yes/no questions (e.g., "Is lead time over 150 days?") to reach a prediction. Easy to explain. |
| **Logistic Regression** | Gives each feature a weight and turns the total into a probability of cancellation. Simple baseline. |
| **Random Forest** | An **ensemble** of many decision trees that each vote. Usually more accurate and less likely to overfit than one tree. |
| **Support Vector Machine (Linear SVM)** | Finds the best dividing line (boundary) between canceled and kept bookings. We use the linear version because the regular SVM is very slow on 29,000 rows. |

**Metrics we use:**
- **Accuracy** – % of all predictions that are correct
- **Precision** – of the bookings we *flag* as cancellations, % that really cancel
- **Recall** – of the bookings that *really* cancel, % we catch
- **F1 score** – a balance of precision and recall

### 6.1 Train the four models
**What this step does:** Fits each model on the training data. We start with default settings (we tune them later in Evaluation).
"""

decision_tree = DecisionTreeClassifier(random_state=random_state)
decision_tree.fit(X_train_scaled, y_train)

logistic_model = LogisticRegression(max_iter=1000)
logistic_model.fit(X_train_scaled, y_train)

random_forest = RandomForestClassifier(random_state=random_state, n_jobs=-1)
random_forest.fit(X_train_scaled, y_train)

svm_model = LinearSVC(random_state=random_state, max_iter=5000)
svm_model.fit(X_train_scaled, y_train)

print("All four models are trained.")

"""### 6.2 Performance on the training set
**What this step does:** Scores each model on the same data it learned from.

**Why:** The rubric asks us to look at training performance. Comparing it later to test performance shows whether a model is **overfitting** (memorizing the training data instead of learning general patterns).
"""

models = {
    "Decision Tree": decision_tree,
    "Logistic Regression": logistic_model,
    "Random Forest": random_forest,
    "Linear SVM": svm_model,
}

training_results = []
for model_name, model in models.items():
    train_predictions = model.predict(X_train_scaled)
    training_results.append({
        "Model": model_name,
        "Accuracy": accuracy_score(y_train, train_predictions),
        "Precision": precision_score(y_train, train_predictions),
        "Recall": recall_score(y_train, train_predictions),
        "F1": f1_score(y_train, train_predictions),
    })

training_table = pd.DataFrame(training_results).set_index("Model").round(3)
training_table

"""**What the training results tell us:**
- The **Decision Tree** and **Random Forest** score almost perfectly on the training data. That is a warning sign of **overfitting**: they may have memorized the training bookings.
- **Logistic Regression** and **Linear SVM** score lower (around 80% accuracy) but similar to each other. These simpler models cannot memorize as easily, so their training scores are a more honest guess of how they will do on new data.
- We check this in the next section by scoring every model on the **test set**.

## 7. Evaluation

### 7.1 Performance on the test set
**What this step does:** Scores each model on the 20% of bookings it has **never seen**. We also add **AUC** (area under the ROC curve), which measures how well the model ranks risky bookings above safe ones, across all thresholds (0.5 = random guessing, 1.0 = perfect).

**Why:** Test results are the best estimate of real-world performance.
"""

test_results = []
for model_name, model in models.items():
    test_predictions = model.predict(X_test_scaled)

    # AUC needs a score, not just a yes/no prediction
    if model_name == "Linear SVM":
        test_scores = model.decision_function(X_test_scaled)
    else:
        test_scores = model.predict_proba(X_test_scaled)[:, 1]

    test_results.append({
        "Model": model_name,
        "Accuracy": accuracy_score(y_test, test_predictions),
        "Precision": precision_score(y_test, test_predictions),
        "Recall": recall_score(y_test, test_predictions),
        "F1": f1_score(y_test, test_predictions),
        "AUC": roc_auc_score(y_test, test_scores),
    })

test_table = pd.DataFrame(test_results).set_index("Model").round(3)
test_table

"""### 7.2 Training vs. test – checking for overfitting
**What this step does:** Puts training and test accuracy side by side.

**What it tells us:** A big gap between training and test accuracy means overfitting. The single **Decision Tree** has the biggest gap. The **Random Forest** also drops from training to test, but it still has the **highest test score**, because averaging many trees cancels out a lot of the memorizing.
"""

accuracy_compare = pd.DataFrame({
    "Training Accuracy": training_table["Accuracy"],
    "Test Accuracy": test_table["Accuracy"],
})
accuracy_compare["Gap"] = (accuracy_compare["Training Accuracy"] - accuracy_compare["Test Accuracy"]).round(3)
print(accuracy_compare)

accuracy_compare[["Training Accuracy", "Test Accuracy"]].plot(kind="bar", color=["#9DB4CC", "#1F4E79"], figsize=(8, 4))
plt.title("Training vs. test accuracy")
plt.ylabel("Accuracy")
plt.ylim(0.5, 1.12)
plt.xticks(rotation=0)
plt.legend(loc="upper center", ncol=2)
plt.show()

"""### 7.3 ROC curves
**What this step does:** Draws an ROC curve for each model. The x-axis is the **False Positive Rate** (FPR = FP / (FP + TN), kept bookings we wrongly flag) and the y-axis is the **True Positive Rate** (TPR = TP / (TP + FN), real cancellations we catch). The dashed diagonal line is random guessing.

**Why:** ROC curves show performance at **every** threshold, so they are not tied to the 0.5 cutoff. A curve closer to the top-left corner is better.

**What it tells the hotel:** The **Random Forest** curve is the highest (AUC about 0.95), so it is the best at separating risky bookings from safe ones. Logistic Regression and Linear SVM have almost the same curve (both AUC about 0.87), so their lines sit on top of each other. The single Decision Tree has the lowest AUC because it gives very "yes or no" probabilities.
"""

plt.figure(figsize=(7, 6))
for model_name, model in models.items():
    if model_name == "Linear SVM":
        test_scores = model.decision_function(X_test_scaled)
    else:
        test_scores = model.predict_proba(X_test_scaled)[:, 1]
    fpr, tpr, thresholds = roc_curve(y_test, test_scores)
    auc_value = roc_auc_score(y_test, test_scores)
    plt.plot(fpr, tpr, label=f"{model_name} (AUC = {auc_value:.3f})")

plt.plot([0, 1], [0, 1], linestyle="--", color="gray", label="Random guess (AUC = 0.5)")
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC curves on the test set")
plt.legend(loc="lower right")
plt.show()

"""### 7.4 Improving the models – grid search with cross-validation
**What this step does:** Uses `GridSearchCV` to try different settings (hyperparameters) and picks the best combination using **5-fold cross-validation**. In 5-fold CV the training data is split into 5 parts; the model trains on 4 and is checked on the 5th, five times, and the scores are averaged. We use **F1** as the score because we care about catching cancellations, not just overall accuracy.

- **Decision Tree:** limit how deep the tree can grow (`max_depth`) and the minimum bookings per leaf (`min_samples_leaf`) to reduce overfitting.
- **Random Forest:** try different numbers of trees (`n_estimators`) and depths.

**Why:** This is how we tune a model without peeking at the test set. *(This cell takes about 1–2 minutes in Colab.)*
"""

# --- Decision Tree grid search ---
tree_settings = {
    "max_depth": [5, 10, 15, 20],
    "min_samples_leaf": [1, 5, 10],
}
tree_search = GridSearchCV(DecisionTreeClassifier(random_state=random_state),
                           tree_settings, cv=5, scoring="f1", n_jobs=-1)
tree_search.fit(X_train_scaled, y_train)
print("Best Decision Tree settings:", tree_search.best_params_)
print("Best Decision Tree CV F1:", round(tree_search.best_score_, 3))

# --- Random Forest grid search ---
forest_settings = {
    "n_estimators": [100, 200],
    "max_depth": [None, 20],
}
forest_search = GridSearchCV(RandomForestClassifier(random_state=random_state),
                             forest_settings, cv=5, scoring="f1", n_jobs=-1)
forest_search.fit(X_train_scaled, y_train)
print("Best Random Forest settings:", forest_search.best_params_)
print("Best Random Forest CV F1:", round(forest_search.best_score_, 3))

# Score the tuned models on the test set
tuned_models = {
    "Decision Tree (tuned)": tree_search.best_estimator_,
    "Random Forest (tuned)": forest_search.best_estimator_,
}

tuned_results = []
for model_name, model in tuned_models.items():
    test_predictions = model.predict(X_test_scaled)
    test_scores = model.predict_proba(X_test_scaled)[:, 1]
    train_accuracy = accuracy_score(y_train, model.predict(X_train_scaled))
    tuned_results.append({
        "Model": model_name,
        "Train Accuracy": train_accuracy,
        "Test Accuracy": accuracy_score(y_test, test_predictions),
        "Precision": precision_score(y_test, test_predictions),
        "Recall": recall_score(y_test, test_predictions),
        "F1": f1_score(y_test, test_predictions),
        "AUC": roc_auc_score(y_test, test_scores),
    })

