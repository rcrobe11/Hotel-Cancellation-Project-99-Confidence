"""### 7.8 Cumulative response and lift
**What this step does:** Ranks test bookings from highest to lowest predicted risk. The **cumulative response curve** shows what % of all cancellations we catch if we only contact the top X% riskiest bookings. **Lift** compares that to picking bookings at random (lift = rate of cancellations among the bookings we target ÷ overall cancellation rate).

**Why:** Hotels have limited staff time. This shows how much better the model is than guessing.

**What it tells the hotel:** A lift **greater than 1** means the model beats random selection. By contacting just the top 10% riskiest bookings, the hotel reaches cancellations about **3 times** more often than picking at random.
"""

ranking_df = pd.DataFrame({"actual": y_test.values, "probability": final_probabilities})
ranking_df = ranking_df.sort_values("probability", ascending=False).reset_index(drop=True)

total_bookings = len(ranking_df)
total_cancellations = ranking_df["actual"].sum()
overall_cancel_rate = total_cancellations / total_bookings

ranking_df["percent_targeted"] = (ranking_df.index + 1) / total_bookings * 100
ranking_df["percent_cancellations_caught"] = ranking_df["actual"].cumsum() / total_cancellations * 100
ranking_df["lift"] = (ranking_df["actual"].cumsum() / (ranking_df.index + 1)) / overall_cancel_rate

# lift at the top 10%, 20%, 30%, and 50%
lift_rows = []
for percent in [10, 20, 30, 50]:
    row_number = int(total_bookings * percent / 100) - 1
    lift_rows.append({
        "Top % of bookings targeted": percent,
        "% of all cancellations caught": round(ranking_df.loc[row_number, "percent_cancellations_caught"], 1),
        "Lift": round(ranking_df.loc[row_number, "lift"], 2),
    })
lift_table = pd.DataFrame(lift_rows)
print(lift_table)

fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
axes[0].plot(ranking_df["percent_targeted"], ranking_df["percent_cancellations_caught"], color="#1F4E79", label="Random Forest")
axes[0].plot([0, 100], [0, 100], linestyle="--", color="gray", label="Random")
axes[0].set_title("Cumulative response curve")
axes[0].set_xlabel("% of bookings targeted (riskiest first)")
axes[0].set_ylabel("% of all cancellations caught")
axes[0].legend()

axes[1].plot(ranking_df["percent_targeted"], ranking_df["lift"], color="#E07B39", label="Random Forest")
axes[1].axhline(1, linestyle="--", color="gray", label="Random (lift = 1)")
axes[1].set_title("Lift curve")
axes[1].set_xlabel("% of bookings targeted (riskiest first)")
axes[1].set_ylabel("Lift")
axes[1].set_xlim(1, 100)
axes[1].legend()

plt.tight_layout()
plt.show()

"""### 7.9 Profit curve – how many rooms should the hotel overbook?
**What this step does:** Puts dollar values on the model's decisions. ROC and lift do not include costs, but a profit curve does. We use **simple example assumptions**:
- If we overbook a room for a booking that **really cancels** (TP), the hotel gains one night of revenue, about the **average room price** (~$103).
- If we overbook a room for a guest who **does show up** (FP), the hotel pays about **$150** to move that guest to another hotel and make up for it.

We then add up profit as we target more and more of the riskiest bookings.

**Why:** The "best" model or threshold depends on business costs and how many bookings the hotel can act on.

**What it tells the hotel:** Profit rises at first (we are mostly catching real cancellations), peaks when we target about the **riskiest 27%** of bookings (a predicted probability of about 0.59 or higher), and then falls when we start overbooking guests who will show up. The peak tells the hotel how much of its booking list it can safely overbook. *(These dollar values are assumptions for illustration; the hotel should replace them with its own numbers.)*
"""

benefit_true_positive = clean_df["avg_price_per_room"].mean()   # revenue saved, about one night
cost_false_positive = 150                                       # cost to relocate a guest who shows up
print("Benefit per correct overbooking: $", round(benefit_true_positive, 2))
print("Cost per wrong overbooking: $", cost_false_positive)

ranking_df["cumulative_tp"] = ranking_df["actual"].cumsum()
ranking_df["cumulative_fp"] = (1 - ranking_df["actual"]).cumsum()
ranking_df["profit"] = ranking_df["cumulative_tp"] * benefit_true_positive - ranking_df["cumulative_fp"] * cost_false_positive

best_row = ranking_df["profit"].idxmax()
best_percent = ranking_df.loc[best_row, "percent_targeted"]
best_profit = ranking_df.loc[best_row, "profit"]
best_threshold = ranking_df.loc[best_row, "probability"]
print("Best % of bookings to target:", round(best_percent, 1), "%")
print("Probability cutoff at that point:", round(best_threshold, 2))
print("Estimated profit on the test set: $", round(best_profit, 0))

plt.figure(figsize=(8, 4.5))
plt.plot(ranking_df["percent_targeted"], ranking_df["profit"] / 1000, color="#1F4E79")
plt.axhline(0, color="gray", linestyle="--")
plt.scatter(best_percent, best_profit / 1000, color="#E07B39", zorder=5, s=60,
            label=f"Best: target top {best_percent:.0f}%  (${best_profit/1000:,.0f}K)")
plt.title("Profit curve – overbooking with the Random Forest")
plt.xlabel("% of bookings targeted (riskiest first)")
plt.ylabel("Profit on test set ($ thousands)")
plt.legend()
